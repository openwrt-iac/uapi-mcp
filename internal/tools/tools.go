// Package tools wires the generated endpoint catalog into MCP tools: one
// tool per uapi endpoint, one HTTP request per call, responses passed through
// as received and errors surfaced with the endpoint, the HTTP status and
// uapi's error envelope verbatim.
package tools

import (
	"context"
	_ "embed"
	"encoding/json"
	"fmt"
	"net/http"
	"net/url"
	"strings"

	"github.com/modelcontextprotocol/go-sdk/mcp"

	"github.com/openwrt-iac/uapi-mcp/internal/client"
)

//go:embed catalog.json
var catalogJSON []byte

// bodyKind tells the handler where the request body comes from.
const (
	bodyNone    = ""        // reads and deletes
	bodyFlat    = "flat"    // no path parameters: the arguments are the body
	bodyWrapped = "wrapped" // the body is the "body" argument
)

// Endpoint is one catalog entry, generated by internal/gen from uapi's
// OpenAPI spec.
type Endpoint struct {
	Tool        string         `json:"tool"`
	Summary     string         `json:"summary"`
	Method      string         `json:"method"`
	Path        string         `json:"path"`
	PathParams  []string       `json:"pathParams,omitempty"`
	QueryParams []string       `json:"queryParams,omitempty"`
	Paginated   bool           `json:"paginated,omitempty"`
	BodyKind    string         `json:"bodyKind,omitempty"`
	Input       map[string]any `json:"input"`
}

func Register(s *mcp.Server, c *client.Client) error {
	var catalog struct {
		UAPIVersion string     `json:"uapi_version"`
		Endpoints   []Endpoint `json:"endpoints"`
	}
	if err := json.Unmarshal(catalogJSON, &catalog); err != nil {
		return fmt.Errorf("decoding embedded catalog: %w", err)
	}
	for _, ep := range catalog.Endpoints {
		s.AddTool(&mcp.Tool{
			Name:        ep.Tool,
			Description: ep.Summary,
			InputSchema: ep.Input,
			Annotations: annotationsFor(ep.Method),
		}, handler(c, ep))
	}
	return nil
}

// annotationsFor tells the host the truth about the verb. Reads only read;
// delete and replace rewrite or drop sections, and every verb but create and
// adopt can be repeated with the same effect.
func annotationsFor(method string) *mcp.ToolAnnotations {
	readOnly := method == http.MethodGet
	idempotent := readOnly ||
		method == http.MethodPut ||
		method == http.MethodPatch ||
		method == http.MethodDelete
	destructive := method == http.MethodDelete || method == http.MethodPut
	openWorld := false
	return &mcp.ToolAnnotations{
		ReadOnlyHint:    readOnly,
		IdempotentHint:  idempotent,
		DestructiveHint: &destructive,
		OpenWorldHint:   &openWorld,
	}
}

func handler(c *client.Client, ep Endpoint) mcp.ToolHandler {
	return func(ctx context.Context, req *mcp.CallToolRequest) (*mcp.CallToolResult, error) {
		args := map[string]any{}
		if len(req.Params.Arguments) > 0 {
			if err := json.Unmarshal(req.Params.Arguments, &args); err != nil {
				return errorResult("invalid arguments: " + err.Error()), nil
			}
		}

		path := ep.Path
		for _, name := range ep.PathParams {
			value, ok := args[name].(string)
			if !ok {
				return errorResult("missing required string argument " + name), nil
			}
			path = strings.ReplaceAll(path, "{"+name+"}", url.PathEscape(value))
		}
		query := url.Values{}
		for _, name := range ep.QueryParams {
			if value, ok := args[name].(string); ok && value != "" {
				query.Set(name, value)
			}
		}

		var body []byte
		var err error
		switch ep.BodyKind {
		case bodyNone:
		case bodyFlat:
			// A body object is the wrapped shape; silently dropping it
			// would send an empty object, and an empty merge-patch is a
			// silent no-op that answers 2xx.
			if _, ok := args["body"]; ok {
				return errorResult("this tool takes the resource fields directly as arguments, not a body object"), nil
			}
			own := map[string]any{}
			for name, value := range args {
				if !ep.owns(name) {
					own[name] = value
				}
			}
			body, err = json.Marshal(own)
		case bodyWrapped:
			value, ok := args["body"]
			if !ok {
				return errorResult("missing required argument body"), nil
			}
			body, err = json.Marshal(value)
		default:
			err = fmt.Errorf("unknown body kind %q", ep.BodyKind)
		}
		if err != nil {
			return errorResult(err.Error()), nil
		}

		if ep.Paginated {
			list, err := c.List(ctx, path, query)
			if err != nil {
				return errorResultFor(err), nil
			}
			return textResult(string(list)), nil
		}
		resp, err := c.Do(ctx, ep.Method, path, query, body)
		if err != nil {
			if ep.Method == http.MethodDelete && client.IsNotFound(err) {
				return textResult(fmt.Sprintf("%s %s: 404 Not Found (already absent)", ep.Method, path)), nil
			}
			return errorResultFor(err), nil
		}
		if len(resp.Body) == 0 {
			return textResult(fmt.Sprintf("%s %s: %d %s", ep.Method, path, resp.Status, http.StatusText(resp.Status))), nil
		}
		text := string(resp.Body)
		if footer := resp.Footer(); footer != "" {
			text += "\n\n" + footer
		}
		return textResult(text), nil
	}
}

// owns reports whether an argument name belongs to the endpoint plumbing
// rather than to a flat body.
func (ep Endpoint) owns(name string) bool {
	if name == "body" {
		return true
	}
	for _, p := range ep.PathParams {
		if p == name {
			return true
		}
	}
	for _, p := range ep.QueryParams {
		if p == name {
			return true
		}
	}
	return false
}

func errorResultFor(err error) *mcp.CallToolResult {
	return &mcp.CallToolResult{
		IsError: true,
		Content: []mcp.Content{&mcp.TextContent{
			Text: err.Error(),
		}},
	}
}

func errorResult(text string) *mcp.CallToolResult {
	return &mcp.CallToolResult{
		IsError: true,
		Content: []mcp.Content{&mcp.TextContent{
			Text: "uapi-mcp " + text,
		}},
	}
}

func textResult(text string) *mcp.CallToolResult {
	return &mcp.CallToolResult{
		Content: []mcp.Content{&mcp.TextContent{
			Text: text,
		}},
	}
}
